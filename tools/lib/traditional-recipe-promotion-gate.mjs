const IDENTITY_PLACEHOLDER = /经核验|身份不明|未知野菜|地方植物/u;
const CANONICAL_ORIGIN = 'https://yiguochu.pages.dev';
const CANONICAL_BASE = 'https://yiguochu.pages.dev/recipes.html?id=';

function entries(value, key) {
  return Array.isArray(value?.[key]) ? value[key] : [];
}

function indexById(items) {
  return new Map(items.map(item => [item?.id, item]));
}

function duplicateErrors(promotions, key) {
  const seen = new Set();
  const errors = [];
  for (const promotion of promotions) {
    const value = promotion?.[key];
    if (seen.has(value)) errors.push(`promotion manifest duplicates ${key} ${value}`);
    else seen.add(value);
  }
  return errors;
}

function findIdentityPlaceholder(value) {
  if (typeof value === 'string') return IDENTITY_PLACEHOLDER.test(value) ? value : undefined;
  if (Array.isArray(value)) {
    for (const item of value) {
      const placeholder = findIdentityPlaceholder(item);
      if (placeholder) return placeholder;
    }
  }
  if (value && typeof value === 'object') {
    for (const item of Object.values(value)) {
      const placeholder = findIdentityPlaceholder(item);
      if (placeholder) return placeholder;
    }
  }
  return undefined;
}

function recipeIdentityPlaceholder(recipe) {
  return findIdentityPlaceholder([
    recipe?.core_ingredients,
    recipe?.optional_ingredients,
    recipe?.generation_optional_ingredients,
    recipe?.generation_liquid_ingredients,
    recipe?.generation_boundaries,
    recipe?.substitution_slots,
  ]);
}

function hasNonEmptyString(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function hasCanonicalSource(recipe, canonicalPath) {
  const expectedUrl = `${CANONICAL_ORIGIN}${canonicalPath}`;
  return entries(recipe, 'source_refs').some(ref => (
    ref?.usage === 'approved'
      && ref?.url === expectedUrl
      && hasNonEmptyString(ref?.title)
      && hasNonEmptyString(ref?.license)
      && hasNonEmptyString(ref?.attribution)
      && hasNonEmptyString(ref?.retrieved_at)
  ));
}

function expectedCanonicalPath(recipeId) {
  return `/recipes.html?id=${recipeId}`;
}

export function hasOnlyExpectedMissingProductionErrors(errors, promotions) {
  const promotionEntries = Array.isArray(promotions) ? promotions : promotions?.promotions;
  if (!Array.isArray(errors) || errors.length === 0 || !Array.isArray(promotionEntries)) return false;
  const expectedErrors = new Set(promotionEntries.map(
    promotion => `${promotion?.recipe_id} missing production recipe`,
  ));
  return errors.every(error => expectedErrors.has(error));
}

export function validateTraditionalRecipePromotion({ candidates, drafts, production, promotions, matrix = PROMOTION_MATRIX }) {
  const errors = [];
  const candidateEntries = entries(candidates, 'entries');
  const draftEntries = entries(drafts, 'drafts');
  const productionEntries = entries(production, 'recipes');
  const promotionEntries = Array.isArray(promotions) ? promotions : promotions?.promotions;
  const actualPromotions = Array.isArray(promotionEntries) ? promotionEntries : [];
  const expectedMatrix = matrix instanceof Map ? matrix : PROMOTION_MATRIX;

  if (actualPromotions.length !== expectedMatrix.size) {
    errors.push(`promotion manifest must contain exactly ${expectedMatrix.size} promotions`);
  }
  for (const key of ['recipe_id', 'draft_id', 'candidate_id']) {
    errors.push(...duplicateErrors(actualPromotions, key));
  }

  const promotionsByRecipeId = new Map(actualPromotions.map(promotion => [promotion?.recipe_id, promotion]));
  for (const [recipeId, expected] of expectedMatrix) {
    const promotion = promotionsByRecipeId.get(recipeId);
    if (!promotion) {
      errors.push(`expected promotion ${recipeId} is missing`);
      continue;
    }
    if (promotion.draft_id !== expected.draft_id) errors.push(`${recipeId} must use draft_id ${expected.draft_id}`);
    if (promotion.candidate_id !== expected.candidate_id) errors.push(`${recipeId} must use candidate_id ${expected.candidate_id}`);
    if (promotion.family_id !== expected.family_id) errors.push(`${recipeId} must use family_id ${expected.family_id}`);
  }
  for (const promotion of actualPromotions) {
    if (!expectedMatrix.has(promotion?.recipe_id)) errors.push(`unexpected promotion ${promotion?.recipe_id} is present`);
  }

  const candidatesById = indexById(candidateEntries);
  const draftsById = indexById(draftEntries);
  const productionById = indexById(productionEntries);
  for (const promotion of actualPromotions) {
    const recipeId = promotion?.recipe_id;
    const canonicalPath = promotion?.canonical_path;
    const requiredCanonicalPath = expectedCanonicalPath(recipeId);
    const candidate = candidatesById.get(promotion?.candidate_id);
    const draft = draftsById.get(promotion?.draft_id);
    const recipe = productionById.get(recipeId);

    if (!candidate) errors.push(`${recipeId} missing candidate ${promotion?.candidate_id}`);
    else if (candidate.status !== 'candidate') errors.push(`${recipeId} linked candidate ${promotion.candidate_id} must have status candidate`);
    if (!draft) errors.push(`${recipeId} missing draft ${promotion?.draft_id}`);
    else {
      if (draft.status !== 'draft') errors.push(`${recipeId} linked draft ${promotion.draft_id} must have status draft`);
      if (draft.candidate_id !== promotion.candidate_id) errors.push(`${recipeId} draft candidate_id must equal ${promotion.candidate_id}`);
    }
    if (!recipe) {
      errors.push(`${recipeId} missing production recipe`);
      continue;
    }
    if (recipe.status !== 'approved') errors.push(`${recipeId} production status must be approved`);
    if (recipe.origin_candidate_id !== promotion.candidate_id) {
      errors.push(`${recipeId} origin_candidate_id must equal ${promotion.candidate_id}`);
    }
    if (canonicalPath !== requiredCanonicalPath) {
      errors.push(`${recipeId} canonical_path must equal ${requiredCanonicalPath}`);
    }
    const placeholder = recipeIdentityPlaceholder(recipe);
    if (placeholder) errors.push(`${recipeId} contains identity placeholder ${placeholder}`);
    if (canonicalPath === requiredCanonicalPath && !hasCanonicalSource(recipe, canonicalPath)) {
      errors.push(`${recipeId} canonical source must use ${CANONICAL_BASE}${recipeId}`);
    }
  }
  return errors;
}
